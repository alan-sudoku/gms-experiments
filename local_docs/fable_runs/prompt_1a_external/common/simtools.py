"""Shared helpers for the Prompt 1a external simulation test run.

Drives two third-party solvers (installed under ~/opt/sim, see ../README.md):
  - GetDP 3.5 + gmsh 4.15: 2-D harmonic eddy current, A_z formulation with an imposed
    net current per conductor region (massive conductors).
  - FastHenry2: 3-D quasi-static filament (PEEC) solver.

This module only writes solver input, runs the solver and parses its output. All physics
is in the solvers. Every result is level `derived` (simulation, not measurement).

Units: SI (metres, S/m) in this module's API. FastHenry input is written in mm.
Phasors: peak. R' = Re(Z) per metre, with Z = -U/I (GetDP's U is the drop with E = -(dA/dt + ur)).
"""
import math
import os
import re
import subprocess
import time
from pathlib import Path

import numpy as np

MU0 = 4e-7 * math.pi
S_CU = 5.96e7          # same values as prompt_1a_code/eddy2d.py
S_AL = 3.77e7

SIM = Path.home() / "opt" / "sim"
GETDP = SIM / "bin" / "getdp"
FASTHENRY = SIM / "bin" / "fasthenry"
WORK = SIM / "work"


def delta(sigma, f):
    return 1.0 / math.sqrt(math.pi * f * MU0 * sigma)


def bessel_round_wire_ratio(a, sigma, f):
    """Exact R_ac/R_dc of an isolated round wire (scipy Bessel functions, complex arg)."""
    from scipy.special import jv
    k = (1 - 1j) / delta(sigma, f)
    return float((k * a / 2 * jv(0, k * a) / jv(1, k * a)).real)


def run_logged(cmd, cwd, log_name, success_marker=None):
    """Run a command, return (wall seconds, peak RSS kB). Raises on failure.

    success_marker: if given, success means this text is in the log, and the exit code
    is ignored (FastHenry2's main() has no return statement, so its exit code is junk)."""
    t = time.time()
    with open(Path(cwd) / log_name, "w") as log:
        p = subprocess.run(["/usr/bin/time", "-f", "MAXRSS_KB %M"] + [str(c) for c in cmd],
                           cwd=cwd, stdout=log, stderr=subprocess.STDOUT)
    wall = time.time() - t
    text = (Path(cwd) / log_name).read_text(errors="replace")
    m = re.search(r"MAXRSS_KB (\d+)", text)
    ok = (success_marker in text) if success_marker else (p.returncode == 0)
    if not ok:
        raise RuntimeError(f"{cmd[0]} failed ({p.returncode}), see {Path(cwd) / log_name}")
    return wall, int(m.group(1)) if m else -1


# =====================================================================  GetDP 2-D
GETDP_PRO = r"""
// 2-D harmonic eddy current, A_z formulation, one imposed current per conductor region.
// Generated by simtools.py. Region tags: conductors 1..NC, air 1000, outer boundary 2000.
DefineConstant[ freq = 1 ];
Group {
  Air = Region[1000]; Bnd = Region[2000];
  @CGROUPS@
  DomainC = Region[{@CLIST@}];
  Domain = Region[{DomainC, Air}];
}
Function {
  nu[] = 1/(4e-7*Pi);
  @SIGMA@
}
Constraint {
  { Name a_bnd; Case { { Region Bnd; Value 0.; } } }
  { Name I_set; Case { @ICASES@ } }
  { Name U_set; Case { } }
}
Jacobian { { Name Vol; Case { { Region All; Jacobian Vol; } } } }
Integration { { Name I1; Case { { Type Gauss; Case {
  { GeoElement Triangle; NumberOfPoints 4; } { GeoElement Line; NumberOfPoints 4; } } } } } }
FunctionSpace {
  { Name Hcurl_a; Type Form1P;
    BasisFunction { { Name se; NameOfCoef ae; Function BF_PerpendicularEdge;
                      Support Domain; Entity NodesOf[All]; } }
    Constraint { { NameOfCoef ae; EntityType NodesOf; NameOfConstraint a_bnd; } } }
  { Name Hregion_u; Type Form1P;
    BasisFunction { { Name sr; NameOfCoef ur; Function BF_RegionZ;
                      Support DomainC; Entity DomainC; } }
    GlobalQuantity { { Name U; Type AliasOf; NameOfCoef ur; }
                     { Name I; Type AssociatedWith; NameOfCoef ur; } }
    Constraint { { NameOfCoef U; EntityType Region; NameOfConstraint U_set; }
                 { NameOfCoef I; EntityType Region; NameOfConstraint I_set; } } }
}
Formulation {
  { Name MagDyn; Type FemEquation;
    Quantity {
      { Name a; Type Local; NameOfSpace Hcurl_a; }
      { Name ur; Type Local; NameOfSpace Hregion_u; }
      { Name I; Type Global; NameOfSpace Hregion_u [I]; }
      { Name U; Type Global; NameOfSpace Hregion_u [U]; } }
    Equation {
      Galerkin { [ nu[] * Dof{d a}, {d a} ]; In Domain; Jacobian Vol; Integration I1; }
      Galerkin { DtDof [ sigma[] * Dof{a}, {a} ]; In DomainC; Jacobian Vol; Integration I1; }
      Galerkin { [ sigma[] * Dof{ur}, {a} ]; In DomainC; Jacobian Vol; Integration I1; }
      Galerkin { DtDof [ sigma[] * Dof{a}, {ur} ]; In DomainC; Jacobian Vol; Integration I1; }
      Galerkin { [ sigma[] * Dof{ur}, {ur} ]; In DomainC; Jacobian Vol; Integration I1; }
      GlobalTerm { [ Dof{I}, {U} ]; In DomainC; } } }
}
Resolution {
  { Name Res;
    System { { Name A; NameOfFormulation MagDyn; Type ComplexValue; Frequency freq; } }
    Operation { Generate[A]; Solve[A]; SaveSolution[A]; } }
}
PostProcessing {
  { Name Post; NameOfFormulation MagDyn;
    Quantity {
      { Name U; Value { Term { [ {U} ]; In DomainC; } } }
      { Name I; Value { Term { [ {I} ]; In DomainC; } } }
      { Name P; Value { Integral { [ 0.5*sigma[]*SquNorm[Dt[{a}]+{ur}] ];
                        In DomainC; Jacobian Vol; Integration I1; } } }
      { Name Area; Value { Integral { [ 1 ]; In DomainC; Jacobian Vol; Integration I1; } } } } }
}
PostOperation {
  { Name Out; NameOfPostProcessing Post;
    Operation {
      Print[ U, OnRegion DomainC, Format RegionTable, File "U.txt" ];
      Print[ I, OnRegion DomainC, Format RegionTable, File "I.txt" ];
      Print[ P[DomainC], OnGlobal, Format Table, File "P.txt" ];
      Print[ Area[DomainC], OnGlobal, Format Table, File "A.txt" ]; } }
}
"""


def _region_table(path):
    """Parse a GetDP 'Format Table' OnRegion file: rows of (region, re, im)."""
    rows = []
    for line in Path(path).read_text().split("\n"):
        v = line.split()
        if len(v) >= 3 and not line.lstrip().startswith("#"):
            rows.append((int(float(v[0])), float(v[-2]) + 1j * float(v[-1])))
    return rows


def _global_value(path):
    v = Path(path).read_text().split()
    return float(v[-2]) if len(v) >= 2 else float(v[-1])


def mesh_2d(build, msh_path, h_surf, h_far, r_inf, d_fine):
    """Mesh a 2-D geometry with gmsh.

    build(occ) must add conductor surfaces and return a list of (tag, region_id).
    The air is a disk of radius r_inf minus the conductors. Element size is h_surf within
    d_fine of every conductor boundary, growing linearly to h_far at 0.5*r_inf.
    Returns number of triangles."""
    import gmsh
    gmsh.initialize()
    gmsh.option.setNumber("General.Verbosity", 1)
    try:
        gmsh.model.add("m")
        occ = gmsh.model.occ
        conds = build(occ)
        disk = occ.addDisk(0, 0, 0, r_inf, r_inf)
        out, _ = occ.fragment([(2, disk)], [(2, t) for t, _ in conds])
        occ.synchronize()
        cond_tags = {t for t, _ in conds}
        # after fragment, conductor tags are kept; air is whatever surface remains
        surfs = [t for d, t in gmsh.model.getEntities(2)]
        air = [t for t in surfs if t not in cond_tags]
        by_region = {}
        for t, rid in conds:
            by_region.setdefault(rid, []).append(t)
        for rid, tags in by_region.items():
            gmsh.model.addPhysicalGroup(2, tags, rid)
        gmsh.model.addPhysicalGroup(2, air, 1000)
        bnd = [c for d, c in gmsh.model.getBoundary([(2, t) for t in air], oriented=False)
               if d == 1]
        cond_curves = set()
        for t in cond_tags:
            cond_curves.update(c for d, c in gmsh.model.getBoundary([(2, t)], oriented=False))
        outer = [c for c in bnd if c not in cond_curves]
        gmsh.model.addPhysicalGroup(1, outer, 2000)
        fd = gmsh.model.mesh.field.add("Distance")
        gmsh.model.mesh.field.setNumbers(fd, "CurvesList", sorted(cond_curves))
        gmsh.model.mesh.field.setNumber(fd, "Sampling", 400)
        ft = gmsh.model.mesh.field.add("Threshold")
        gmsh.model.mesh.field.setNumber(ft, "InField", fd)
        gmsh.model.mesh.field.setNumber(ft, "SizeMin", h_surf)
        gmsh.model.mesh.field.setNumber(ft, "SizeMax", h_far)
        gmsh.model.mesh.field.setNumber(ft, "DistMin", d_fine)
        gmsh.model.mesh.field.setNumber(ft, "DistMax", 0.5 * r_inf)
        gmsh.model.mesh.field.setAsBackgroundMesh(ft)
        for k in ("MeshSizeFromPoints", "MeshSizeFromCurvature", "MeshSizeExtendFromBoundary"):
            gmsh.option.setNumber("Mesh." + k, 0)
        gmsh.option.setNumber("Mesh.Algorithm", 6)
        gmsh.option.setNumber("Mesh.MshFileVersion", 4.1)
        gmsh.model.mesh.generate(2)
        _, tags, _ = gmsh.model.mesh.getElements(2)
        ntri = sum(len(t) for t in tags)
        gmsh.write(str(msh_path))
        return ntri
    finally:
        gmsh.finalize()


def getdp_solve(workdir, msh_path, f, sigmas, currents):
    """Solve one frequency. sigmas, currents: dicts region_id -> value (S/m, A peak).
    Returns dict with Z per region (U/I), total loss P [W/m], area, R_loss = 2P/|sum I|^2."""
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    cg = " ".join(f"C_{r} = Region[{r}];" for r in sigmas)
    cl = ", ".join(f"C_{r}" for r in sigmas)
    sig = "\n  ".join(f"sigma[C_{r}] = {s!r};" for r, s in sigmas.items())
    ic = " ".join(f"{{ Region C_{r}; Value {complex(i).real!r}; }}"
                  for r, i in currents.items())
    pro = (GETDP_PRO.replace("@CGROUPS@", cg).replace("@CLIST@", cl)
           .replace("@SIGMA@", sig).replace("@ICASES@", ic))
    (workdir / "eddy.pro").write_text(pro)
    for fn in ("U.txt", "I.txt", "P.txt", "A.txt"):
        (workdir / fn).unlink(missing_ok=True)
    wall, rss = run_logged([GETDP, "eddy.pro", "-msh", Path(msh_path).resolve(),
                            "-setnumber", "freq", repr(float(f)),
                            "-solve", "Res", "-pos", "Out", "-v", "2"],
                           workdir, "getdp.log")
    U = dict(_region_table(workdir / "U.txt"))
    I = dict(_region_table(workdir / "I.txt"))
    P = _global_value(workdir / "P.txt")
    A = _global_value(workdir / "A.txt")
    Itot = sum(I.values())
    return dict(U=U, I=I, P=P, area=A, R_loss=2 * P / abs(Itot) ** 2,
                Z={r: -U[r] / I[r] for r in U}, wall=wall, rss_kb=rss)


# =====================================================================  FastHenry
FH_SIGMA_SCALE = 1e-3     # S/m -> S/mm (FastHenry: sigma in 1/(units*ohm), units = mm)


class FHDeck:
    """Builds a FastHenry input deck in mm."""

    def __init__(self, title):
        self.lines = [f"* {title}", ".units mm"]
        self.n_nodes = 0
        self.n_segs = 0

    def node(self, name, x, y, z):
        self.lines.append(f"N{name} x={x*1e3:.9g} y={y*1e3:.9g} z={z*1e3:.9g}")
        self.n_nodes += 1

    def seg(self, name, n1, n2, w, h, sigma, nw=1, nh=1, rw=1.0, rh=1.0, wdir=None):
        s = (f"E{name} N{n1} N{n2} w={w*1e3:.9g} h={h*1e3:.9g} "
             f"sigma={sigma*FH_SIGMA_SCALE:.9g} nwinc={nw} nhinc={nh} rw={rw} rh={rh}")
        if wdir is not None:
            s += f" wx={wdir[0]} wy={wdir[1]} wz={wdir[2]}"
        self.lines.append(s)
        self.n_segs += 1

    def equiv(self, names):
        names = list(names)
        for i in range(0, len(names), 50):       # keep lines short
            chunk = names[i:i + 50] if i == 0 else [names[0]] + names[i:i + 50]
            self.lines.append(".equiv " + " ".join(f"N{n}" for n in chunk))

    def port(self, n1, n2):
        self.lines.append(f".external N{n1} N{n2}")

    def freqs(self, fs):
        for f in fs:
            self.lines.append(f".freq fmin={f:.9g} fmax={f:.9g} ndec=1")

    def write(self, path):
        Path(path).write_text("\n".join(self.lines + [".end", ""]))


def fh_parse_zc(path):
    """Parse Zc.mat for a 1-port deck: list of (f, Z complex)."""
    out = []
    text = Path(path).read_text()
    for m in re.finditer(r"Impedance matrix for frequency = (\S+) 1 x 1\s*\n\s*(\S+)\s*([+-]\S+)j",
                         text):
        out.append((float(m.group(1)), float(m.group(2)) + 1j * float(m.group(3))))
    return out


def fh_run(workdir, deck, extra_args=()):
    """Write and run a deck. Returns (list of (f, Z), wall s, peak RSS kB)."""
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    deck.write(workdir / "deck.inp")
    (workdir / "Zc.mat").unlink(missing_ok=True)
    wall, rss = run_logged([FASTHENRY, "deck.inp", *extra_args], workdir, "fasthenry.log",
                           success_marker="All impedance matrices dumped")
    return fh_parse_zc(workdir / "Zc.mat"), wall, rss


def fh_solid_bar(name, W, T, L, sigma, f_list, nw, nh, rw=1.0, rh=1.0):
    """Deck for a single solid W x T bar of length L along z (one segment)."""
    d = FHDeck(name)
    d.node(1, 0, 0, 0)
    d.node(2, 0, 0, L)
    d.seg(1, 1, 2, W, T, sigma, nw, nh, rw, rh, wdir=(1, 0, 0))
    d.port(1, 2)
    d.freqs(f_list)
    return d
